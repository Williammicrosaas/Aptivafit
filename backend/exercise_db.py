def get_exercise_by_id(exercise_id: str):
    for e in EXERCISES:
        if e["id"] == exercise_id:
            return e
    return None


def get_by_group(group: str):
    return [e for e in EXERCISES if e["group"] == group]


def get_groups():
    seen = []
    for e in EXERCISES:
        if e["group"] not in seen:
            seen.append(e["group"])
    return seen
